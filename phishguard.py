def ml_predict(url):
    features = extract_features(url)
    if features is None:
        return (0, None)
    import pandas as pd
    row = pd.DataFrame([features])
    prob = model.predict_proba(row)[0][1]  # probability of being phishing
    if prob >= 0.7:
        return (40, f"ML model flagged this as phishing ({int(prob*100)}% confidence)")
    elif prob >= 0.4:
        return (20, f"ML model finds this suspicious ({int(prob*100)}% confidence)")
    return (0, None)

def analyze(url):
    up = urlparse(url if url.startswith('http') else 'http://' + url)
    rules = [
        scheme(up),
        urlLen(url),
        susWords(url),
        IP(up.netloc),
        dotCheck(up.netloc),
        hyphen(up.netloc),
        at(up.netloc),
        tld(up.netloc),
        brandSpoof(url, up.netloc),
        subdomainAbuse(up.netloc),
        ml_predict(url),        # ← new
    ]
    score = 0
    flags = []
    for points, reason in rules:
        if reason:
            score += points
            flags.append((points, reason))
    return score, flags

def result(score):
    if score <= 20:   return "SAFE"
    elif score <= 50: return "SUSPICIOUS"
    else:             return "DANGEROUS"

def plot_analysis(url, flags, score):
    if not flags:
        print("No flags to visualize — URL appears clean.")
        return

    labels = [reason for _, reason in flags]
    values = [points for points, _ in flags]
    colors = ['#ff4444' if p >= 25 else '#ff9900' if p >= 15 else '#ffcc00' for p in values]

    fig, ax = plt.subplots(figsize=(10, max(3, len(flags) * 0.8)))
    bars = ax.barh(labels, values, color=colors, edgecolor='black', height=0.5)

    for bar, val in zip(bars, values):
        ax.text(bar.get_width() + 0.5, bar.get_y() + bar.get_height()/2,
                f'+{val}', va='center', fontweight='bold')

    verdict = result(score)
    ax.set_xlabel('Risk Points', fontsize=12)
    ax.set_title(f'PhishGuard Analysis\n{url}\n{verdict}  |  Total Score: {score}',
                 fontsize=12, fontweight='bold')
    ax.set_xlim(0, max(values) * 1.3)
    ax.invert_yaxis()
    plt.tight_layout()
    ax.set_title(f'PhishGuard Analysis\n{url}\n|  Total Score: {score}')
    plt.savefig('/content/drive/My Drive/Colab files/phishguard_result.png', dpi=150)
    plt.show()
    print("Chart saved.")

