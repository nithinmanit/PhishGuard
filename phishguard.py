def extract_features(url):
    try:
        up = urlparse(url if url.startswith('http') else 'http://' + url)
        domain = up.netloc
        return {
            'length'        : len(url),
            'has_ip'        : 1 if re.search(r"\d{1,3}(\.\d{1,3}){3}", domain) else 0,
            'num_dots'      : url.count('.'),
            'num_hyphens'   : url.count('-'),
            'num_at'        : 1 if '@' in url else 0,
            'has_https'     : 1 if up.scheme == 'https' else 0,
            'sus_words'     : sum(1 for w in ['login','verify','secure','update','bank','account'] if w in url.lower()),
            'num_subdomains': len(domain.split('.')) - 2,
            'sus_tld'       : 1 if domain.split('.')[-1].lower() in {'xyz','top','gq','tk','ml','cf','ga','click'} else 0,
            'long_str'      : 1 if re.search(r"[a-z0-9]{10,}", domain) else 0,
            'num_slashes'   : url.count('/'),
            'num_params'    : len(up.query.split('&')) if up.query else 0,
        }
    except:
        return None

