def scheme(url):
    if url.scheme != 'https':
      return (15, "Uses HTTP instead of HTTPS")
    return (0, None)

def urlLen(url):
    if len(url) > 75:
      return (10, f"Url is suspiciously long. {len(url)} characters.")
    return (0, None)

def susWords(url):
    sw = ['login', 'verify', 'secure', 'update', 'bank', 'account']
    found = [w for w in sw if w in url]
    if found:
      return (10, f"Suspicious words found: {', '.join(found)}")
    return (0, None)

def IP(d):
    if re.search(r"\d{1,3}(\.\d{1,3}){3}", d):
      return (25, "Url uses IP address as domain name")
    return (0, None)

def dotCheck(d):
    dots = len(re.findall(r"\.", d))
    if dots > 4:
      return (15, "Contains too many dots.")
    return (0, None)

def hyphen(d):
    hyphen = len(re.findall(r"\-", d))
    if hyphen > 3:
      return (15, "Contains too many hyphens.")
    return (0, None)

def at(d):
    if re.search(r"\@", d):
      return (20, "Url contains '@'.")
    return (0, None)

def tld(d):
    susTLD = {'xyz', 'top', 'gq', 'tk', 'ml', 'cf', 'ga', 'click', 'work', 'support'}
    tld = d.split('.')[-1].lower()
    if tld in susTLD:
      return (10, "Sus TLD")
    return (0, None)

def brandSpoof(u, d, brands= BRANDS):
    for brand in brands:
      if re.search(rf"{brand}", u.lower()) and not re.search(rf"{brand}", d):
        return (25, f"Brand name {brand} found in a different part")
    return (0, None)

def randStr(d):
    if re.search(r"[a-z0-9]{10,}", d):
      return (10, "Long random string detected")
    return (0, None)

def subdomainAbuse(d):
    parts = d.split('.')
    if len(parts) > 4:
        return (15, f"Suspicious number of subdomains ({len(parts)-2})")
    return (0, None)

